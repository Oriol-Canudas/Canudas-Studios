const {editReply,openOptions}=require('./conversation-controls.cjs');
const {chromium}=require(process.env.QA_PLAYWRIGHT||'playwright');
const assert=require('node:assert/strict'),fs=require('fs');
(async()=>{
 const {initialPrep,reducePrep,initialNegotiation,BUILD,negotiationOpening}=await import('../src/engine.mjs');
 const prep=['visit:lia','cost','plan'].reduce(reducePrep,initialPrep());
 const browser=await chromium.launch({headless:true,executablePath:process.env.QA_CHROME||undefined});
 const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'}),page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));let requests=[],release;
 await page.route('**/api/negotiate',async route=>{
  if(route.request().method()==='GET')return route.fulfill({json:{available:true}});
  const b=route.request().postDataJSON();
  if(b.action==='start')return route.fulfill({json:{token:'fixture-token',negotiation:initialNegotiation(),opening:negotiationOpening(prep)}});
  requests.push(b);
  if(requests.length===1)return route.fulfill({status:502,json:{error:'generation_failed'}});
  await new Promise(r=>{release=r});
  return route.fulfill({json:{token:'next-fixture-token',negotiation:{...initialNegotiation(),turns:1},reply:{text:'Què vols conservar d’aquesta cançó?',cue:'Et mira.',mood:'guarded'},diagnostic:{source:'mock',missing:['proposal']}}});
 });
 await page.goto(process.env.QA_URL||'http://127.0.0.1:8785');
 await page.evaluate(({prep,BUILD})=>localStorage.setItem('perspectives-concert-encore-v05',JSON.stringify({build:BUILD,screen:'brief',prep})),{prep,BUILD});await page.reload();
 const click=name=>page.getByRole('button',{name,exact:true}).click();
 await click('Talk to Lia');await editReply(page);await page.locator('#message').fill('Vull un final honest.');await click('Send message');await page.getByRole('alert').waitFor();
 await editReply(page);assert.equal(await page.locator('#message').inputValue(),'Vull un final honest.');
 assert((await page.locator('.turns-left').innerText()).includes('6 turns'));
 await page.locator('#message').press('Enter');await page.getByRole('status').waitFor();await editReply(page);assert.equal(await page.locator('#message').inputValue(),'');
 assert(await page.getByRole('button',{name:'Send message',exact:true}).isDisabled());
 assert(await page.getByRole('button',{name:'Review & end',exact:true}).isDisabled());
 await editReply(page);await page.locator('#message').fill('Aquest és el següent pensament.');
 await page.setViewportSize({width:390,height:480});await page.locator('#message').focus();await page.waitForTimeout(150);
 const box=await page.getByRole('button',{name:'Send message',exact:true}).boundingBox();assert(box.y+box.height<=480);
 release();await page.getByText('Què vols conservar d’aquesta cançó?',{exact:true}).waitFor();
 assert.equal(requests.length,2);assert.equal(requests[0].requestId,requests[1].requestId);
 assert.equal(await page.locator('#message').inputValue(),'Aquest és el següent pensament.');
 await page.screenshot({path:'qa/10-keyboard-sized.png'});
 await click('Send message');await page.getByRole('status').waitFor();
 await openOptions(page);await click('PERSPECTIVES · start again');await click('Start again');
 release();await page.waitForTimeout(200);assert(await page.getByRole('button',{name:'Enter backstage',exact:true}).isVisible());
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('perspectives-concert-encore-v05')));assert.equal(saved.negotiation.turns,0);assert.equal(saved.screen,'cover');assert.equal(errors.length,0);
 fs.writeFileSync('qa/resilience-results.json',JSON.stringify({scope:'Mock backend; actual browser UI. Keyboard-sized viewport, not real iOS keyboard.',pass:true,checks:['failed request preserves draft and turns','retry keeps request id','in-flight send and close disabled','new draft survives previous reply','send remains visible at 390x480','late reply after restart ignored'],errors},null,2));
 await browser.close();console.log('Mocked UI resilience checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
